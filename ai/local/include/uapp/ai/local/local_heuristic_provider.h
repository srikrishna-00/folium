// ###########################################################################
// ##                                                                       ##
// ##   THIS IS NOT ARTIFICIAL INTELLIGENCE. IT IS NOT A MODEL OF ANY KIND.  ##
// ##                                                                       ##
// ##   No neural network, no transformer, no statistical model, no weights, ##
// ##   no training data, no inference. It is word-frequency arithmetic,     ##
// ##   keyword matching and byte-pattern scanning — techniques that predate ##
// ##   machine learning by decades.                                        ##
// ##                                                                       ##
// ##   OUTPUT FROM THIS PROVIDER MUST NEVER BE PRESENTED TO A USER AS       ##
// ##   "AI", "AI-generated", "AI-written", "generated by a model", or       ##
// ##   anything that implies a model produced it.                          ##
// ##                                                                       ##
// ##   Spec §5 forbids pretending unsupported functionality works. Labelling##
// ##   these outputs as AI would be the most consequential possible form of ##
// ##   that, because a user's trust calibration for "the AI summarised your ##
// ##   contract" is very different from their calibration for "we picked    ##
// ##   the three most distinctive sentences out of your contract".          ##
// ##                                                                       ##
// ##   The enforcement is not this comment. Every result carries            ##
// ##   `ResultMeta::provenance == OutputProvenance::HeuristicNoModel`, set  ##
// ##   by AIProvider's non-virtual wrapper from this provider's descriptor, ##
// ##   so a UI has to read a field that says "no model" and choose to       ##
// ##   ignore it.                                                          ##
// ##                                                                       ##
// ###########################################################################
//
// ===========================================================================
// WHY IT EXISTS
// ===========================================================================
// An interface with no implementation is a guess. This environment has no
// network access to any AI provider API and no local model weights, so the
// only way to find out whether `AIProvider` is a workable interface — whether
// its request/result shapes, its error codes, its consent boundary and its
// output validation actually hold up — is to write a real implementation
// behind it and run it. That is what this is.
//
// It is also genuinely useful on its own merits for three of the seven
// capabilities. Extractive summarisation, keyword classification and pattern
// extraction are techniques people shipped products on for thirty years. They
// are weak compared to a language model and strong compared to nothing, they
// run in microseconds on the ADR-0002 decision 3 device floor, they need no
// download, and they never leave the device.
//
// ===========================================================================
// WHAT IT DOES, PER CAPABILITY
// ===========================================================================
//
//  summarize()  IMPLEMENTED — EXTRACTIVE.
//      Splits the input into sentences, scores each by smoothed TF-IDF over
//      the input's own sentences (see ai/local/src/text_analysis.h for the
//      exact formula), and returns the N highest-scoring sentences IN
//      DOCUMENT ORDER. Every sentence is a verbatim span of the input, and
//      `SummarizeResult::source_spans` gives the byte offsets, so the output
//      is checkable against the source. This is NOT truncation: a strong
//      sentence in the middle of a document beats a weak one at the top.
//      It is also NOT abstractive — it cannot condense two sentences into
//      one, cannot rephrase, and will happily select a sentence that only
//      makes sense in context.
//
//  classify()   IMPLEMENTED — KEYWORD/RULE-BASED.
//      Scores each caller-supplied label by whole-word occurrences of its
//      hint phrases (and its display name), with diminishing returns per
//      repeat, then normalises to a confidence. **It ABSTAINS when no hint
//      matches** rather than returning its least-bad guess, because a
//      confident wrong category attached to a user's document is worse than
//      no category. `builtin_document_labels()` ships a ready-made label set
//      for common document kinds.
//
//  extract()    IMPLEMENTED — PATTERN-BASED.
//      Emails, http/https URLs, calendar-validated ISO-8601 dates, signed
//      integers/decimals, and currency amounts — each with its byte span in
//      the input, overlaps arbitrated. Hand-written scanners, not std::regex
//      (ADR-0001 bans exceptions; std::regex throws). Ambiguous dates like
//      `03/04/2026` are deliberately NOT extracted; see text_analysis.h.
//
//  embed()      IMPLEMENTED — LEXICAL FINGERPRINT, NOT SEMANTIC.
//      256-dimensional signed hashing over word unigrams plus character
//      3-grams, L2-normalised. Deterministic; near-duplicates land near each
//      other. **"car" and "automobile" are orthogonal.** Semantic search
//      built on this would be worse than the FTS5 index the product already
//      has. It exists so the `embed()` capability has something real behind
//      it and so a 384-dim model has a slot to drop into
//      (ai-architecture.md §6). Honestly a placeholder, and labelled one.
//
//  generate()   NOT IMPLEMENTED — `Status::AiCapabilityNotImplemented`.
//  chat()       NOT IMPLEMENTED — `Status::AiCapabilityNotImplemented`.
//  translate()  NOT IMPLEMENTED — `Status::AiCapabilityNotImplemented`.
//
//      These three need a language model. There is no honest heuristic for
//      them: you cannot approximate "write a paragraph about this" or
//      "render this sentence in French" with word frequencies. The tempting
//      alternative — returning a canned string, or echoing the input, or
//      returning the first sentence and calling it generation — is exactly
//      the fabrication spec §5 forbids, and it would be worse than an error
//      because the caller could not tell. So they return a specific status
//      saying this provider does not do that, and the matching capability
//      bits are CLEAR in the descriptor, so the registry never routes to them
//      in the first place.

#ifndef UAPP_AI_LOCAL_LOCAL_HEURISTIC_PROVIDER_H
#define UAPP_AI_LOCAL_LOCAL_HEURISTIC_PROVIDER_H

#include <cstdint>
#include <vector>

#include "uapp/ai/provider.h"

namespace uapp::ai::local {

/// Embedding width this provider declares.
///
/// WHY 256 AND NOT 384: 384 is the dimension ai-architecture.md §6 specifies
/// for the real MiniLM/BGE-small-class model. Using it here would make a
/// hash fingerprint and a real embedding indistinguishable by shape, and the
/// one thing a vector store must never do is mix two models' vectors in one
/// space (AIQ-5, §13.4). A deliberately different width makes the mistake
/// impossible to make silently.
inline constexpr std::uint32_t kLocalHeuristicEmbedDim = 256;

/// Stable provider id. `kind:name` shaped, and `heuristic` rather than
/// `model` on purpose — this string appears in logs, in consent records and
/// in the user's model picker.
inline constexpr const char* kLocalHeuristicProviderId = "local-heuristic:v1";

/// A ready-made `ClassifyLabel` set for common document kinds, usable with
/// `classify()` out of the box.
///
/// Hand-written hints, not learned: invoice/receipt/resume/meeting notes/
/// source code/correspondence. The list is deliberately short and the hints
/// deliberately specific, because a keyword classifier's failure mode is
/// over-matching on a generic word. It is offered as a default, not as a
/// taxonomy — a caller is expected to supply its own labels, which is why the
/// vocabulary lives in the REQUEST and not in the provider.
[[nodiscard]] std::vector<ClassifyLabel> builtin_document_labels();

/// See the banner at the top of this file. Not AI.
class LocalHeuristicProvider final : public AIProvider {
public:
    LocalHeuristicProvider();

    /// `clock` exists only so the consent-expiry check in the base class is
    /// testable; this provider is on-device and never consults it.
    explicit LocalHeuristicProvider(ClockFn clock);

    [[nodiscard]] const ProviderDescriptor& descriptor() const noexcept override {
        return descriptor_;
    }

    /// Always `Healthy`. There is nothing to be unhealthy about: no model
    /// file, no socket, no quota. A provider that cannot fail to be available
    /// should say so rather than inventing a probe.
    [[nodiscard]] Health health() const noexcept override { return Health::Healthy; }

protected:
    // --- NOT IMPLEMENTED. See the banner. ---------------------------------
    [[nodiscard]] Status do_generate(const GenerateRequest&, GenerateResult&) override;
    [[nodiscard]] Status do_chat(const ChatRequest&, ChatResult&) override;
    [[nodiscard]] Status do_translate(const TranslateRequest&, TranslateResult&) override;

    // --- real implementations ---------------------------------------------
    [[nodiscard]] Status do_embed(const EmbedRequest&, EmbedResult&) override;
    [[nodiscard]] Status do_summarize(const SummarizeRequest&, SummarizeResult&) override;
    [[nodiscard]] Status do_classify(const ClassifyRequest&, ClassifyResult&) override;
    [[nodiscard]] Status do_extract(const ExtractRequest&, ExtractResult&) override;

private:
    ProviderDescriptor descriptor_;
};

}  // namespace uapp::ai::local

#endif  // UAPP_AI_LOCAL_LOCAL_HEURISTIC_PROVIDER_H
