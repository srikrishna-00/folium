// core/notes/note.h — the note value type and its validation rules.
//
// A "note" here is the minimum viable ancestor of the `document` + `block`
// model in database-design.md section 3.3. It is deliberately flat (one title,
// one body string) for this vertical slice; the block tree, CBOR payloads,
// fractional sort keys and CRDT state are later phases. The *identifier*
// already matches the real design (16-byte opaque id stored as a BLOB) so that
// growing into the real schema does not require an id migration.

#ifndef UAPP_CORE_NOTES_NOTE_H
#define UAPP_CORE_NOTES_NOTE_H

#include <array>
#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>

#include "uapp/status.h"

namespace uapp::notes {

/// Hard limits. These are enforced at the domain boundary so that nothing
/// unbounded ever reaches the storage adapter (spec section 38: "Validate
/// buffer sizes", "Validate external input").
inline constexpr std::size_t kNoteIdBytes     = 16;
inline constexpr std::size_t kNoteIdHexChars  = kNoteIdBytes * 2;
inline constexpr std::size_t kMaxTitleBytes   = 512;
inline constexpr std::size_t kMaxBodyBytes    = 4u * 1024u * 1024u;  // 4 MiB
inline constexpr std::size_t kMaxQueryBytes   = 1024;
inline constexpr std::size_t kMaxSearchLimit  = 1000;

/// An opaque 128-bit note identifier.
///
/// Rendered as 32 lowercase hex characters for humans and CLIs; stored as raw
/// bytes. `parse` is the only way to build one from untrusted text and it
/// validates length and alphabet -- there is no "trust me" constructor.
class NoteId final {
public:
    constexpr NoteId() noexcept = default;

    explicit constexpr NoteId(const std::array<std::uint8_t, kNoteIdBytes>& raw) noexcept
        : bytes_(raw) {}

    /// Parse 32 hex characters (either case accepted, lowercase emitted).
    /// Returns Status::NoteIdMalformed for anything else. Never partially
    /// writes `out` on failure.
    [[nodiscard]] static Status parse(std::string_view hex, NoteId& out) noexcept;

    [[nodiscard]] std::string to_hex() const;

    [[nodiscard]] const std::array<std::uint8_t, kNoteIdBytes>& bytes() const noexcept {
        return bytes_;
    }

    /// A default-constructed id. Treated as "unset", never persisted.
    [[nodiscard]] bool is_nil() const noexcept;

    friend bool operator==(const NoteId& a, const NoteId& b) noexcept {
        return a.bytes_ == b.bytes_;
    }
    friend bool operator!=(const NoteId& a, const NoteId& b) noexcept { return !(a == b); }

private:
    std::array<std::uint8_t, kNoteIdBytes> bytes_{};
};

/// The note itself. A plain value type: copying it is cheap enough at this
/// size and avoids any question of shared ownership.
struct Note final {
    NoteId        id;
    std::string   title;
    std::string   body;
    std::int64_t  created_at_ms  = 0;  ///< Unix epoch milliseconds, UTC
    std::int64_t  modified_at_ms = 0;
};

/// A single full-text search result. `snippet` is generated by the search
/// index and already has the match delimited; it is a fragment of the body,
/// so callers must treat it as user content (never log it).
struct SearchHit final {
    NoteId      id;
    std::string title;
    std::string snippet;
    double      rank = 0.0;  ///< lower is a better match (BM25 convention)
};

/// Validate the mutable fields of a note. Called by NoteService before every
/// write; also safe for callers to use up front to give early UI feedback.
[[nodiscard]] Status validate_title(std::string_view title) noexcept;
[[nodiscard]] Status validate_body(std::string_view body) noexcept;
[[nodiscard]] Status validate_note(const Note& note) noexcept;

}  // namespace uapp::notes

#endif  // UAPP_CORE_NOTES_NOTE_H
