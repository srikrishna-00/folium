// core/search/search_result.h — what one unified search hit looks like.
//
// Spec section 16 wants ONE query that searches "Notes, Pages, PDFs, DOCX,
// Images through OCR, ... file names, metadata, databases". This run
// implements the first two source kinds (see the NOT IMPLEMENTED list at the
// bottom of this header). The result type is therefore deliberately shaped
// around "which kind of object matched, and which ids do I need to open it",
// not around any one domain's value type.
//
// WHY RAW `ObjectIdBytes` AND NOT NoteId / PageId / BlockId
// ---------------------------------------------------------------------------
// core/search must not depend on core/notes or core/blocks. If it did, every
// future source kind (PDF page, OCR region, file name) would make this module
// depend on one more domain, and the search layer would end up linking the
// whole product. The 16 bytes are the one thing every id in the system
// already agrees on (core/common/object_id.h), so that is what crosses the
// boundary; a caller that knows it asked about notes reconstructs a
// `notes::NoteId` from `source_id` in one line, and the build graph keeps
// core/search honest (core/search links uapp::core_common and nothing else).

#ifndef UAPP_CORE_SEARCH_SEARCH_RESULT_H
#define UAPP_CORE_SEARCH_SEARCH_RESULT_H

#include <cstddef>
#include <string>

#include "uapp/object_id.h"
#include "uapp/status.h"

namespace uapp::search {

/// Which kind of object a hit names. Values are PERSISTED in the search
/// index's `source_kind` column: append-only, never renumber, never reuse.
///
/// Note and Page/Block are implemented. The rest of spec section 16's list
/// (PDF, DOCX, OCR'd image, scanned document, file name, metadata, database
/// row) is NOT IMPLEMENTED and deliberately has NO enumerator here: a value
/// with no indexer behind it is a promise this enum cannot keep, and it would
/// silently become a persisted number nothing writes.
enum class SourceKind : std::int32_t {
    /// A whole `notes::Note` — title and body indexed as one unit.
    Note = 0,
    /// A `blocks::Page`, indexed for its TITLE only. The page's text lives in
    /// its blocks and is indexed as Block entries, one per block.
    Page = 1,
    /// One `blocks::Block`'s plain text. `container_id` is the page it is on.
    Block = 2,
};

/// Number of SourceKind values that exist. Used to bound-check the integer
/// read back out of the index, which comes from an attacker-reachable file.
inline constexpr std::int32_t kSourceKindCount = 3;

/// Stable lowercase identifier ("note", "page", "block"). Never null;
/// returns "unknown" for an out-of-range integer cast into the enum. This is
/// what goes into logs and (later) the C ABI — not the localised label.
[[nodiscard]] const char* source_kind_name(SourceKind kind) noexcept;

[[nodiscard]] bool source_kind_is_valid(SourceKind kind) noexcept;

/// One hit, ranked.
struct SearchResult final {
    /// Which kind of object matched. Decides how to read the two ids.
    SourceKind kind = SourceKind::Note;

    /// The id of the thing that matched: a note id, a page id, or a block id.
    ObjectIdBytes source_id{};

    /// The id of the object that CONTAINS the match, when the match is not
    /// itself openable. For Block this is the page id — which is what a UI
    /// needs to navigate ("open page Y, scroll to block X"). Nil for Note and
    /// Page, which are their own containers.
    ObjectIdBytes container_id{};

    /// The containing object's title: the note's title, the page's title, or
    /// — for a Block — the title of the page it sits on, so a result list can
    /// be grouped and labelled without a second query per row.
    std::string title;

    /// The match in context, with the matched terms delimited by '[' and ']'.
    /// Generated by the index. This is a fragment of USER CONTENT: never log
    /// it (spec section 34).
    std::string snippet;

    /// Relevance. BM25 convention: LOWER (more negative) is a better match.
    /// Comparable across kinds — see the single-table argument in
    /// storage/sqlite/src/search_index_sql.h.
    double rank = 0.0;
};

/// Hard limits, enforced at the port boundary so nothing unbounded reaches
/// the index (spec section 38: "Validate buffer sizes", "Validate external
/// input").

/// Longest raw query string accepted. Matches `notes::kMaxQueryBytes`; a
/// static_assert in the SQLite adapter keeps the two from drifting.
inline constexpr std::size_t kMaxQueryBytes = 1024;

/// Ceiling on `limit`. A caller asking for more gets this many.
inline constexpr std::size_t kMaxResults = 1000;

}  // namespace uapp::search

#endif  // UAPP_CORE_SEARCH_SEARCH_RESULT_H
